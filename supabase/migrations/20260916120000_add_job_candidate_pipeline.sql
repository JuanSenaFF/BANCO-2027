  ('adzuna_br', 'adzuna', 'Adzuna Brasil', 'https://api.adzuna.com/v1/api/jobs/br', 3, false, true,
   250, null, 'credentials_missing', '{"role":"discovery","confidence":"medium","requires_terms_review":true}'::jsonb),
  ('jooble_br', 'jooble', 'Jooble Brasil', 'https://br.jooble.org/api', 4, false, true,
